from html import escape

def create_email_template(report):
    """Convert a ResearchReport into a formatted HTML email."""

    findings_html = ""

    for finding in report.key_findings:
        findings_html += f"<li>{escape(finding)}</li>"

    sources_html = ""

    for source in report.sources:
        title = escape(source.title)
        url = escape(source.url, quote=True)
        snippet = escape(source.snippet)

        sources_html += f"""
        <li style="margin-bottom: 14px;">
            <a href="{url}">{title}</a>
            <p>{snippet}</p>
        </li>
        """

    html_content = f"""
    <html>
    <body style="font-family: Arial, sans-serif;
                 line-height: 1.6; color: #222;">

        <div style="max-width: 700px; margin: auto;">

            <h1 style="color: #1f4e79;">
                AI Research Report
            </h1>

            <hr>

            <h2>Research Question</h2>
            <p>{escape(report.research_question)}</p>

            <h2>Executive Summary</h2>
            <p>{escape(report.summary)}</p>

            <h2>Key Findings</h2>
            <ul>
                {findings_html}
            </ul>

            <h2>Sources</h2>
            <ol>
                {sources_html}
            </ol>

            <hr>

            <p style="font-size: 12px; color: #777;">
                Generated by your AI Research Assistant.
            </p>

        </div>
    </body>
    </html>
    """

    return html_content
